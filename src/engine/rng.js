/**
 * Seeded RNG (mulberry32) so every player's daily game is byte-identical:
 * the day's seed drives shuffles, opening hands, and the bot's plan.
 */
function mulberry(a0) {
  let a = a0 >>> 0;
  const next = () => {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  return {
    next,
    int: (n) => Math.floor(next() * n),
    range: (lo, hi) => lo + Math.floor(next() * (hi - lo + 1)),
    pick: (arr) => arr[Math.floor(next() * arr.length)],
    shuffle: (arr) => {
      const a2 = [...arr];
      for (let i = a2.length - 1; i > 0; i--) {
        const j = Math.floor(next() * (i + 1));
        [a2[i], a2[j]] = [a2[j], a2[i]];
      }
      return a2;
    },
    /** Deterministic seed from a string (used for the date seed). */
    state: () => a,
  };
}

export function makeRng(seed) { return mulberry(seed); }

/** Restore an RNG from a serialized counter so a resumed run replays identically. */
export function rngFromState(state) { return mulberry(Number(state) >>> 0 || 1); }

export function hashSeed(str) {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}
